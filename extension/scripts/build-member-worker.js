import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

// Deterministic classic-Worker bundle of internal ESM adapters, no dependency
// installation or duplicate hand-maintained execution implementation.
export function bundleMemberWorker(readSource = url => readFileSync(url, 'utf8')) {
  const modules = ['server-time', 'site-rules', 'member-journal-store', 'site-controller', 'member-execution-client', 'member-access', 'member-execution-loop'];
  let output = '// Generated by scripts/build-member-worker.js; edit src modules.\nconst FocurveMemberExecution = (() => {\nconst modules = {};\n';
  for (const name of modules) {
    let source = readSource(new URL('../src/' + name + '.js', import.meta.url)).replace(/\r\n/g, '\n');
    const exports = [...source.matchAll(/export (?:class|function|const) (\w+)/g)].map(match => match[1]);
    source = source.replace(/^import '\.\.\/background\/(?:host-policy|member-events)\.js';\n/gm, '');
    source = source.replace(/import \{ ([^}]+) \} from '\.\/([^']+)\.js';/g,
      (_all, names, dependency) => `const { ${names} } = modules['${dependency}'];`);
    if (/\bimport\b/.test(source.replace(/\/\/[^\n]*/g, ''))) throw new Error('Unsupported bundle import');
    source = source.replace(/export (class|function|const) /g, '$1 ');
    output += `modules['${name}'] = (() => {\n${source}\nreturn { ${exports.join(', ')} };\n})();\n`;
  }
  return output + "return Object.freeze({...modules['member-execution-client'], ...modules['member-execution-loop'],...modules['member-journal-store'],...modules['member-access']});\n})();\n";
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url))
  writeFileSync(new URL('../background/member-execution.js', import.meta.url), bundleMemberWorker());
