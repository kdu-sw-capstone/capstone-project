import { readFileSync, writeFileSync } from 'node:fs';
import { posix, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export function buildDnrWriter() {
  const root = new URL('../', import.meta.url);
  const names = ['a1/contract.mjs', 'src/additional-dnr-inventory.js', 'src/additional-dnr-store.js', 'member-a1/db.mjs', 'src/additional-dnr-legacy-writer.js'];
  const modules = names.map(name => {
    let source = readFileSync(new URL(name, root), 'utf8').replace(/\r\n/g, '\n');
    const exports = [...source.matchAll(/export (?:async )?(?:class|function|const) (\w+)/g)].map(m => m[1]);
    source = source.replace(/import (\w+) from ['"]([^'"]+\.json)['"] with \{[^}]+\};/g,
      (_m, n, path) => 'const ' + n + '=' + readFileSync(new URL(posix.join(posix.dirname(name), path), root), 'utf8').replace(/\r\n/g, '\n') + ';');
    source = source.replace(/import \{([^}]+)\} from ['"]([^'"]+)['"];?/g,
      (_m, n, path) => 'const {' + n + '}=modules[' + JSON.stringify(posix.join(posix.dirname(name), path)) + '];');
    source = source.replace(/export (async |class |function |const )/g, '$1');
    return 'modules[' + JSON.stringify(name) + ']=(()=>{' + source + ';return {' + exports.join(',') + '};})();\n';
  }).join('');
  return '// Generated by scripts/build-dnr-writer.mjs; edit source modules.\n(()=>{const modules={};\n' + modules
    + "modules['src/additional-dnr-legacy-writer.js'].installMemberDnrWriter(chrome,indexedDB,navigator.locks);\n})();\n";
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url))
  writeFileSync(new URL('../background/additional-dnr-writer.bundle.js', import.meta.url), buildDnrWriter());
